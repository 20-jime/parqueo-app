-- =====================================================
-- Diseño de base de datos: Parqueo de automóviles
-- Motor: PostgreSQL
-- Todas las tablas llevan el prefijo PRQ
-- =====================================================

CREATE TABLE prq_automoviles (
    id_automovil INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color        VARCHAR(30) NOT NULL,
    anio         INT         NOT NULL CHECK (anio BETWEEN 1900 AND 2100),
    fabricante   VARCHAR(50) NOT NULL,
    tipo         VARCHAR(10) NOT NULL CHECK (tipo IN ('Sedan', '4x4', 'Moto'))
);

CREATE TABLE prq_parqueo (
    id_parqueo       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_provincia VARCHAR(50)   NOT NULL,
    nombre           VARCHAR(100)  NOT NULL,
    precio_por_hora  NUMERIC(10,2) NOT NULL CHECK (precio_por_hora >= 0)
);

CREATE TABLE prq_ingreso_automoviles (
    consecutivo         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_parqueo          INT       NOT NULL REFERENCES prq_parqueo (id_parqueo),
    id_automovil        INT       NOT NULL REFERENCES prq_automoviles (id_automovil),
    fecha_hora_entrada  TIMESTAMP NOT NULL,
    fecha_hora_salida   TIMESTAMP NULL,  -- NULL = el automóvil aún no ha salido
    CONSTRAINT ck_prq_ingreso_fechas
        CHECK (fecha_hora_salida IS NULL OR fecha_hora_salida >= fecha_hora_entrada)
);